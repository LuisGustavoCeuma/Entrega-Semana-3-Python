def somar(a, b):
    '''Função somar'''

    return a + b

def subtrair(a, b):
    '''Função subtrair'''

    return a - b

def multiplicar(a, b):
    '''Função multiplicar'''

    return a * b

def dividir(a, b):
    '''Função dividir'''

    if b == 0:
        return "Não é possivel dividir por 0."
    else:
        return a / b
